CREATE OR REPLACE FUNCTION "public"."reorder_albums"("updates" "jsonb") RETURNS "void"
    LANGUAGE "plpgsql" SECURITY DEFINER
    AS $$
DECLARE item JSONB; BEGIN
  FOR item IN SELECT * FROM jsonb_array_elements(updates) LOOP
    UPDATE albums SET display_order = (item->>'display_order')::INTEGER WHERE id = (item->>'id')::UUID AND is_owner();
  END LOOP;
END; $$;


ALTER FUNCTION "public"."reorder_albums"("updates" "jsonb") OWNER TO "postgres";


